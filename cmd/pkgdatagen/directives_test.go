func TestGenerateDirectiveMemberIdentity(t *testing.T) {
	const pkgPath = "example.com/fixture"
	t.Chdir(t.TempDir())
	require.NoError(t, os.WriteFile("go.mod", []byte("module "+pkgPath+"\n\ngo 1.26.0\n"), 0o644))
	require.NoError(t, os.WriteFile("dep.go", []byte(`package fixture

type Base struct{}
type alias = Base
type Alias = alias
//xgols:notrecommended
func (*alias) Hidden() {}
func (*Base) Visible() {}
type pointerAlias = *Base
//xgols:notrecommended
func (pointerAlias) HiddenThroughPointer() {}

type API = interface {
    //xgols:notrecommended
    Read()
}
type OtherAPI interface { Read() }

type hidden struct {
    //xgols:notrecommended
    Key int
    //xgols:notrecommended
    Base
}
type intermediate = hidden
type Public intermediate
type Other struct { Key int; Base }

type internal[T any] struct {
    //xgols:notrecommended
    Item T
}
type Generic internal[int]

type internalPair[A, B any] struct {
    //xgols:notrecommended
    Second B
}
type Pair (internalPair[int, string])

type hiddenReader interface {
    //xgols:notrecommended
    Text() string
}
type Reader hiddenReader
`), 0o644))
	pkg, doc := generateDirectiveTestPackage(t, pkgPath)
	assert.Nil(t, pkg.Scope().Lookup("hidden"))
	for _, tt := range []struct {
		owner, member string
		marked        bool
	}{
		{owner: "Base", member: "Hidden", marked: true},
		{owner: "Alias", member: "Hidden", marked: true},
		{owner: "Base", member: "HiddenThroughPointer", marked: true},
		{owner: "Base", member: "Visible"},
		{owner: "API", member: "Read", marked: true},
		{owner: "OtherAPI", member: "Read"},
		{owner: "Public", member: "Key", marked: true},
		{owner: "Public", member: "Base", marked: true},
		{owner: "Other", member: "Key"},
		{owner: "Other", member: "Base"},
		{owner: "Generic", member: "Item", marked: true},
		{owner: "Pair", member: "Second", marked: true},
		{owner: "Reader", member: "Text", marked: true},
	} {
		owner := pkg.Scope().Lookup(tt.owner)
		require.NotNil(t, owner, tt.owner)
		member, _, _ := gotypes.LookupFieldOrMethod(owner.Type(), true, pkg, tt.member)
		require.NotNil(t, member, "%s.%s", tt.owner, tt.member)
		assert.Equal(t, tt.marked, doc.ObjectMetadata(member).NotRecommended, "%s.%s", tt.owner, tt.member)
	}
}

func TestGenerateDirectivesFromXGoSource(t *testing.T) {
	const pkgPath = "example.com/fixture"
	const source = `package fixture
//xgols:notrecommended
type Hidden = int
type Record struct {
    //xgols:notrecommended
    Field int
    Visible int
}
//xgols:notrecommended
const HiddenConst = 1
func Helper(i int) {}
//xgols:notrecommended
func Choose = (Helper)
`
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "dep.xgo", source, parser.ParseComments)
	require.NoError(t, err)
	xgoPkg := &ast.Package{Name: "fixture", Files: map[string]*ast.File{"dep.xgo": file}}
	compiled, err := cl.NewPackage(pkgPath, xgoPkg, &cl.Config{Fset: fset, Importer: goimporter.Default()})
	require.NoError(t, err)
	var generated bytes.Buffer
	require.NoError(t, compiled.WriteTo(&generated))
	assert.NotContains(t, generated.String(), "//xgols:notrecommended")
	for _, tt := range []struct {
		name, generatedFile, excludedSource string
	}{
		{name: "Package", generatedFile: "xgo_autogen.go", excludedSource: "dep_test.xgo"},
		{name: "PrefixedSingleSource", generatedFile: "xgo_autogen_dep.xgo.go", excludedSource: "unused.xgo"},
		{name: "SuffixedSingleSource", generatedFile: "dep_autogen.go", excludedSource: "unused.xgo"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Chdir(t.TempDir())
			require.NoError(t, os.WriteFile("go.mod", []byte("module "+pkgPath+"\n\ngo 1.26.0\n"), 0o644))
			require.NoError(t, os.WriteFile("dep.xgo", []byte(source), 0o644))
			require.NoError(t, os.WriteFile(tt.generatedFile, generated.Bytes(), 0o644))
			require.NoError(t, os.WriteFile("native.go", []byte(`package fixture
//xgols:notrecommended
const NativeConst = 2
`), 0o644))
			require.NoError(t, os.WriteFile(tt.excludedSource, []byte(`package fixture
//xgols:notrecommended
func Helper() {}
`), 0o644))
			if tt.excludedSource == "unused.xgo" {
				require.NoError(t, os.WriteFile("unused_autogen.go", []byte("package fixture\nconst Unrelated = true\n"), 0o644))
			}

			pkg, doc := generateDirectiveTestPackage(t, pkgPath)
			gogen.InitXGoPackage(pkg)
			for _, name := range []string{"Hidden", "HiddenConst", "NativeConst", "Choose"} {
				obj := pkg.Scope().Lookup(name)
				require.NotNil(t, obj, name)
				assert.True(t, doc.ObjectMetadata(obj).NotRecommended, name)
			}
			helper := pkg.Scope().Lookup("Helper")
			require.NotNil(t, helper)
			assert.False(t, doc.ObjectMetadata(helper).NotRecommended)
			record := generatedNamedType(t, pkg, "Record")
			field, _, _ := gotypes.LookupFieldOrMethod(record, false, pkg, "Field")
			require.NotNil(t, field)
			assert.True(t, doc.ObjectMetadata(field).NotRecommended)
			visible, _, _ := gotypes.LookupFieldOrMethod(record, false, pkg, "Visible")
			require.NotNil(t, visible)
			assert.False(t, doc.ObjectMetadata(visible).NotRecommended)
		})
	}
}

func generateDirectiveTestPackage(t *testing.T, pkgPath string) (*gotypes.Package, *pkgdoc.PkgDoc) {
	t.Helper()

	require.NoError(t, generate([]string{pkgPath}, "pkgdata.zip"))
	archive, err := zip.OpenReader("pkgdata.zip")
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, archive.Close()) })
	pkg, err := gcexportdata.Read(bytes.NewReader(readGeneratedFile(t, archive, pkgPath+".pkgexport")), token.NewFileSet(), make(map[string]*gotypes.Package), pkgPath)
	require.NoError(t, err)
	var doc pkgdoc.PkgDoc
	require.NoError(t, json.Unmarshal(readGeneratedFile(t, archive, pkgPath+".pkgdoc"), &doc))
	return pkg, &doc
}
